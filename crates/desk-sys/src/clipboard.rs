//! Text on the clipboard: read it, write it, and tell when it changed. Who may read or write is
//! decided above this crate; here a clipboard answers `state` without reading the contents, so change
//! detection hands no text to anyone, and only `read_text` reads them. `Marks` carry the conventions
//! password managers use to keep a copy out of clipboard histories (concealed) or to say it is
//! short-lived (transient), both read and written.
//!
//! `os()` is NSPasteboard on macOS and the user32 clipboard on Windows, and `unsupported` on Linux
//! for now; `fake` is a clipboard in memory for tests, here and in the crates above. There is no OS
//! change notification here: `Changes` and `watch` poll `state`.

use std::sync::Arc;
use std::sync::mpsc::{self, RecvTimeoutError, Sender};
use std::thread::{self, JoinHandle};
use std::time::Duration;

use crate::{Error, ErrorCode};

pub mod fake;
#[cfg(target_os = "macos")]
mod macos;
#[cfg(windows)]
mod windows;

/// How a copy asks clipboard histories and monitors to treat it. `Default` is neither.
#[derive(Debug, Clone, Copy, Default, PartialEq, Eq, Hash)]
pub struct Marks {
    /// Keep it out of every history and monitor (a password): macOS
    /// `org.nspasteboard.ConcealedType`; Windows `ExcludeClipboardContentFromMonitorProcessing` or
    /// `Clipboard Viewer Ignore`.
    pub concealed: bool,
    /// Short-lived, not worth keeping (a one-time code): macOS `org.nspasteboard.TransientType` or
    /// `org.nspasteboard.AutoGeneratedType`; Windows `CanIncludeInClipboardHistory` holding 0.
    pub transient: bool,
}

/// What is on the clipboard, without its contents.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash)]
pub struct State {
    /// Changes with every copy, the same text twice included, and never on a read. Compare it for
    /// equality only: it may wrap (Windows' sequence number is 32-bit).
    pub count: u64,
    /// Whether there is text; contents that are not text (an image, files) are not.
    pub has_text: bool,
    pub marks: Marks,
}

/// The system clipboard, text only. A failed OS call is `io_error`.
pub trait Clipboard: Send + Sync {
    /// The count, whether there is text, and the marks. Never reads the contents.
    fn state(&self) -> Result<State, Error>;
    /// The text on the clipboard, `None` when there is none.
    fn read_text(&self) -> Result<Option<String>, Error>;
    /// Replace the clipboard with `text`, marked with `marks`. Text holding a NUL is
    /// `invalid_params`, refused before the clipboard changes.
    fn write_text(&self, text: &str, marks: Marks) -> Result<(), Error>;
}

/// The OS clipboard: NSPasteboard's general pasteboard.
#[cfg(target_os = "macos")]
pub fn os() -> Result<Arc<dyn Clipboard>, Error> {
    Ok(Arc::new(macos::Pasteboard))
}

/// The OS clipboard: user32's, for the whole session. Waits about 100 ms while another app holds it.
#[cfg(windows)]
pub fn os() -> Result<Arc<dyn Clipboard>, Error> {
    Ok(Arc::new(windows::WindowsClipboard::new()?))
}

/// The OS clipboard: none here yet. X11 needs a selection owner thread and Wayland a data-control
/// protocol GNOME lacks, so Linux waits for a source of its own.
#[cfg(not(any(target_os = "macos", windows)))]
pub fn os() -> Result<Arc<dyn Clipboard>, Error> {
    Err(Error::new(
        ErrorCode::Unsupported,
        "the OS clipboard is reachable on macOS and Windows only for now",
    ))
}

/// The `invalid_params` every clipboard answers for text it cannot hold, before it changes anything.
pub(crate) fn check_text(text: &str) -> Result<(), Error> {
    if text.contains('\0') {
        return Err(Error::new(
            ErrorCode::InvalidParams,
            "text with a NUL character cannot go on the clipboard",
        ));
    }
    Ok(())
}

/// Tells each new clipboard state once. It keeps the last count it saw: a poll that sees another
/// answers the new state, and a failed poll answers the error and keeps the count.
#[derive(Debug, Clone)]
pub struct Changes {
    /// `None` until a state has been read; that first state is the baseline, not a change.
    last: Option<u64>,
}

impl Changes {
    /// Starts from the clipboard's current state, so only later copies are changes.
    pub fn new(clipboard: &dyn Clipboard) -> Self {
        Self {
            last: clipboard.state().ok().map(|state| state.count),
        }
    }

    /// The state, if its count differs from the last one seen; several copies between two polls are
    /// one change carrying the latest state.
    pub fn poll(&mut self, clipboard: &dyn Clipboard) -> Result<Option<State>, Error> {
        let state = clipboard.state()?;
        let last = self.last.replace(state.count);
        Ok(match last {
            Some(last) if last != state.count => Some(state),
            _ => None,
        })
    }
}

/// A running clipboard watch. Dropping it stops the watch; once drop returns, the callback has been
/// dropped and is never called again.
pub struct Watch {
    stop: Option<(Sender<()>, JoinHandle<()>)>,
}

impl Drop for Watch {
    fn drop(&mut self) {
        if let Some((stop, thread)) = self.stop.take() {
            let _ = stop.send(());
            // A callback that drops its own watch must not wait for itself.
            if thread.thread().id() != thread::current().id() {
                let _ = thread.join();
            }
        }
    }
}

/// Call `on_change` with each new state of `clipboard`, polled every `every` (at least 1 ms) on one
/// thread named `desk-clipboard`, until the `Watch` is dropped. Copies made after this returns are
/// reported; a failed poll is skipped and the next interval tries again. The caller chooses the
/// interval; `on_change` runs on the watch's thread.
///
/// Panics if the OS cannot start a thread, as `thread::spawn` does.
pub fn watch(
    clipboard: Arc<dyn Clipboard>,
    every: Duration,
    mut on_change: impl FnMut(State) + Send + 'static,
) -> Watch {
    let every = every.max(Duration::from_millis(1));
    let mut changes = Changes::new(clipboard.as_ref());
    let (stop, stopped) = mpsc::channel::<()>();
    let thread = thread::Builder::new()
        .name("desk-clipboard".to_owned())
        .spawn(move || {
            while let Err(RecvTimeoutError::Timeout) = stopped.recv_timeout(every) {
                if let Ok(Some(state)) = changes.poll(clipboard.as_ref()) {
                    on_change(state);
                }
            }
        })
        .expect("the OS starts the desk-clipboard thread");
    Watch {
        stop: Some((stop, thread)),
    }
}
