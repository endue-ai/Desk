// The target's structure of a copied table (PG-63), from the catalog rows PostgreSQL 17 answers for
// `shop.orders`: renamed to the target's schema and name, a serial column's sequence made for it,
// the foreign keys apart (or left out) and pointing at copied tables' copies, and a query's columns
// as a new table.
import { describe, expect, it } from "vitest";
import { keyOf, queryTable, renamed, structureOf, type TableDef } from "../ui/transfer/ddl.js";

const orders: TableDef = {
  schema: "shop",
  name: "orders",
  columns: [
    ["id", "integer", "YES", "nextval('shop.orders_id_seq'::regclass)", "", "", null],
    ["no", "bigint", "YES", null, "d", "", null],
    ["customer_id", "integer", "YES", null, "", "", null],
    ["total", "numeric(10,2)", "NO", "0", "", "", null],
    ["net", "numeric", "NO", "(total / 1.2)", "", "s", null],
  ],
  constraints: [
    ["primary key", "orders_pkey", "PRIMARY KEY (id)", ""],
    ["check", "positive_total", "CHECK (total >= 0::numeric)", ""],
  ],
  indexes: [
    [
      "index",
      "orders_pkey",
      "CREATE UNIQUE INDEX orders_pkey ON shop.orders USING btree (id)",
      "constraint",
    ],
    [
      "index",
      "orders_customer_idx",
      "CREATE INDEX orders_customer_idx ON shop.orders USING btree (customer_id)",
      "",
    ],
  ],
  triggers: [["trigger", "orders_touch", "CREATE TRIGGER orders_touch ...", ""]],
  meta: [["p", "p", null, "RANGE (id)", null, null, null]],
  keys: [
    {
      name: "orders_customer_fk",
      definition: "FOREIGN KEY (customer_id) REFERENCES shop.customers(id)",
      schema: "shop",
      table: "customers",
      shown: "shop.customers",
    },
    {
      name: "orders_region_fk",
      definition: "FOREIGN KEY (customer_id) REFERENCES regions(id)",
      schema: "public",
      table: "regions",
      shown: "regions",
    },
  ],
};

describe("the target's structure", () => {
  it("writes the target's table under its own name", () => {
    const copies = new Map([
      [keyOf("shop", "orders"), { schema: "archive", name: "old_orders" }],
      [keyOf("shop", "customers"), { schema: "archive", name: "customers" }],
    ]);
    const made = structureOf(
      orders,
      { schema: "archive", name: "old_orders" },
      { foreignKeys: true, copies },
    );
    expect(made.create).toBe(
      [
        'CREATE SEQUENCE "archive"."old_orders_id_seq";\n',
        'CREATE TABLE "archive"."old_orders" (',
        `    "id" integer DEFAULT nextval('"archive"."old_orders_id_seq"'::regclass) NOT NULL,`,
        '    "no" bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL,',
        '    "customer_id" integer NOT NULL,',
        '    "total" numeric(10,2) DEFAULT 0,',
        '    "net" numeric GENERATED ALWAYS AS ((total / 1.2)) STORED,',
        '    CONSTRAINT "old_orders_pkey" PRIMARY KEY (id),',
        '    CONSTRAINT "old_orders_positive_total" CHECK (total >= 0::numeric)',
        ");\n",
        'CREATE INDEX "old_orders_customer_idx" ON "archive"."old_orders" USING btree (customer_id);\n',
        'ALTER SEQUENCE "archive"."old_orders_id_seq" OWNED BY "archive"."old_orders"."id";\n',
      ].join("\n"),
    );
    expect(made.keys).toBe(
      [
        'ALTER TABLE "archive"."old_orders" ADD CONSTRAINT "old_orders_customer_fk" FOREIGN KEY (customer_id) REFERENCES "archive"."customers"(id);\n',
        'ALTER TABLE "archive"."old_orders" ADD CONSTRAINT "old_orders_region_fk" FOREIGN KEY (customer_id) REFERENCES "public"."regions"(id);\n',
      ].join(""),
    );
    expect(made.after).toContain(
      `SELECT pg_catalog.setval(pg_catalog.pg_get_serial_sequence('"archive"."old_orders"', 'no'), coalesce(max("no"), 0) + 1, false) FROM "archive"."old_orders";`,
    );
    expect(made.after).toContain(
      `pg_catalog.setval('"archive"."old_orders_id_seq"', coalesce(max("id"), 0) + 1, false)`,
    );
    // A generated column is left out of the COPY on both sides.
    expect(made.columns).toEqual(['"id"', '"no"', '"customer_id"', '"total"']);
    expect(made.notes).toEqual([
      '"shop"."orders" is partitioned: its copy is a plain table that holds every partition\'s rows.',
      '"shop"."orders"\'s trigger is not copied.',
    ]);
  });

  it("keeps the names under the same name, and leaves the foreign keys out when asked", () => {
    const made = structureOf(
      orders,
      { schema: "shop", name: "orders" },
      { foreignKeys: false, copies: new Map() },
    );
    expect(made.create).toContain('CONSTRAINT "positive_total" CHECK');
    expect(made.create).toContain('CREATE INDEX "orders_customer_idx" ON "shop"."orders"');
    expect(made.keys).toBe("");
    expect(renamed("orders_pkey", "orders", "stock")).toBe("stock_pkey");
    expect(renamed("by_day", "orders", "stock")).toBe("stock_by_day");
  });

  it("makes a new table of a query's columns", () => {
    expect(
      queryTable(
        [
          { name: "day", type: "date" },
          { name: "Total", type: "numeric" },
        ],
        { schema: "public", name: "daily" },
      ),
    ).toBe('CREATE TABLE "public"."daily" (\n    "day" date,\n    "Total" numeric\n);\n');
  });
});
