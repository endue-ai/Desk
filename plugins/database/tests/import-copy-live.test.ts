// A file import by COPY on a real server (PG-60), through the desk core's sessions (core-bridge.ts).
// The large file is generated as it is read (fixed-width rows, so any range of it is known without
// holding it), dropped on the plugin, imported into a new table with its columns inferred, and its
// row count and a checksum compared with the generator's, the plugin's heap measured all along. A
// row the server refuses rolls everything back, the table with it; skip mode writes it with the
// server's reason to the reject file and keeps the rest; Cancel leaves nothing. It runs when
// ENDUE_DB_TEST_POSTGRES holds a URI of a scratch database; ENDUE_DB_TEST_IMPORT_MIB sizes the
// large file (2048 MiB by default).
import { mkdtempSync, readFileSync, rmSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { setFlagsFromString } from "node:v8";
import { runInNewContext } from "node:vm";
import { afterAll, beforeAll, describe, expect, it } from "vitest";
import { normalize, parseUri } from "../ui/connections.js";
import type { Connection } from "../ui/engines/common.js";
import type { ImportModel } from "../ui/importer.js";
import { sharedCore } from "./core-bridge";
import { type Mounted, mount } from "./harness";
import { liveSessions } from "./live-sessions";
import { realProcs } from "./scripted";

const uri = process.env.ENDUE_DB_TEST_POSTGRES ?? "";
const { fields, password } = uri ? parseUri(uri) : { fields: {}, password: undefined };
const server = liveSessions(uri, "endue import");
const LIVE = (uri ? normalize({ ...fields, id: "c-live-import", name: "live" }) : {}) as Connection;
const MIB = Number(process.env.ENDUE_DB_TEST_IMPORT_MIB ?? 2048);
const folder = mkdtempSync(join(tmpdir(), "desk-import-"));
setFlagsFromString("--expose-gc");
const gc = runInNewContext("gc") as () => void;
const heap = () => {
  gc();
  return process.memoryUsage().heapUsed;
};

// The generated file: a header, then rows of 66 bytes each.
const HEADER = "id,name,amount,day\n";
const ROW = 66;
const pad = (n: number, width: number) => String(n).padStart(width, "0");
const hex = (n: number) => (Math.imul(n, 2654435761) >>> 0).toString(16).padStart(8, "0");
const nameOf = (i: number) => `${hex(i)}${hex(i + 1)}${hex(i + 2)}${hex(i + 3)}`;
const cents = (i: number) => (i * 7919) % 10_000_000;
const rowOf = (i: number) =>
  `${pad(i, 12)},${nameOf(i)},${pad(Math.floor(cents(i) / 100), 5)}.${pad(cents(i) % 100, 2)},2026-11-${pad((i % 28) + 1, 2)}\n`;
const rowsIn = (bytes: number) => Math.floor((bytes - HEADER.length) / ROW);

/** The generated file's bytes from `offset`, `length` of them. */
function generated(size: number, offset: number, length: number) {
  const end = Math.min(size, offset + length);
  let text = "";
  let at = offset;
  if (at < HEADER.length) {
    text += HEADER.slice(at, end);
    at = Math.min(end, HEADER.length);
  }
  for (let i = Math.floor((at - HEADER.length) / ROW) + 1; at < end; i++) {
    const start = HEADER.length + (i - 1) * ROW;
    const row = rowOf(i);
    text += row.slice(at - start, end - start);
    at = start + ROW;
  }
  return Buffer.from(text, "latin1").toString("base64");
}

/** What the server's checksum of the generated rows comes to. */
function expectedSum(rows: number) {
  // Each row adds less than 2^24, so the sum stays an exact number for billions of rows.
  let sum = 0;
  for (let i = 1; i <= rows; i++)
    sum +=
      (i % 1_000_003) * 7 +
      (cents(i) % 1_000_003) +
      (Number.parseInt(hex(i), 16) % 1_000_003) +
      (i % 28) +
      1;
  return String(sum);
}
const SUM = (table: string) =>
  `SELECT count(*) || ':' || sum((id % 1000003) * 7 + ((amount * 100)::bigint % 1000003) + (('x' || substr(name, 1, 8))::bit(32)::bigint % 1000003) + extract(day from day)::bigint) FROM ${table}`;

type Watch = { reads: number[]; heap: number; first?: () => void };

/** The plugin on the real core; `files` are generated by size, or held as text. */
async function live(files: Record<string, number | string>, watch: Watch, rejects?: string) {
  const procs = realProcs(password ? { password } : {});
  const core = sharedCore();
  const copy = procs.handlers["db.copy"] as (params: { data?: string }) => Promise<unknown>;
  const m = await mount({
    store: { connections: [LIVE] },
    handlers: {
      ...procs.handlers,
      // Each chunk is dropped once sent: the heap shows what the plugin itself holds.
      "db.copy": async (params) => {
        const done = await copy(params);
        params.data = "";
        watch.first?.();
        return done as never;
      },
      "dialog.save": () => ({ cancelled: false, path: rejects ?? "" }),
      "fs.write": async (params) => core.call("fs.write", params) as never,
      "fs.read": async ({ path, offset = 0, length }) => {
        const file = files[path];
        if (file === undefined) throw new Error(`no file ${path}`);
        const size = typeof file === "number" ? file : Buffer.byteLength(file);
        const want = length ?? size;
        const content =
          typeof file === "number"
            ? generated(size, offset, want)
            : Buffer.from(file)
                .subarray(offset, offset + want)
                .toString("base64");
        watch.reads.push(want);
        watch.heap = Math.max(watch.heap, heap());
        return { content, encoding: "base64", size };
      },
    },
  });
  procs.attach((event) => m.host.emit(event));
  return m;
}

const fresh = (): Watch => ({ reads: [], heap: 0 });
const latest = (m: Mounted) => m.view.imports.at(-1) as ImportModel | null;
async function dropped(m: Mounted, path: string) {
  await m.app.drop({ kind: "file", path }, undefined);
  await m.settle();
}

describe.skipIf(!uri)("an import by COPY on a real server", () => {
  beforeAll(async () => {
    await server.end();
    await server.admin("DROP TABLE IF EXISTS big, bad, skip, gone");
  }, 120_000);
  afterAll(async () => {
    await server.end();
    await server.admin("DROP TABLE IF EXISTS big, bad, skip, gone");
    rmSync(folder, { recursive: true, force: true });
  });

  it(`imports a generated file of ${MIB} MiB into a new table with flat memory, count and checksum equal`, async () => {
    const size = HEADER.length + rowsIn(MIB * 1024 * 1024) * ROW;
    const rows = rowsIn(size);
    const watch = fresh();
    const m = await live({ "~/gen/big.csv": size }, watch);
    const before = heap();
    await dropped(m, "~/gen/big.csv");
    expect(latest(m)?.copy?.newColumns).toEqual([
      { name: "id", type: "integer" },
      { name: "name", type: "text" },
      { name: "amount", type: "numeric" },
      { name: "day", type: "date" },
    ]);
    // Ids past 2^31 need a bigint: the person corrects what the sample said.
    m.app.importChange({ column: [0, { type: "bigint" }] });
    await m.settle();
    // The recording view keeps every model it is shown: only the last few matter here.
    const imports = m.view.imports;
    const keep = setInterval(() => imports.splice(0, Math.max(0, imports.length - 4)), 200);
    const began = Date.now();
    await m.app.importRun();
    clearInterval(keep);
    const ms = Date.now() - began;
    expect(m.view.said.at(-1)).toBe(
      `Imported ${rows.toLocaleString("en-US")} rows into big by COPY in one transaction.`,
    );
    expect(await server.admin(SUM("big"))).toBe(`${rows}:${expectedSum(rows)}`);
    expect(Math.max(...watch.reads)).toBeLessThanOrEqual(1024 * 1024);
    const grew = watch.heap - before;
    expect(grew).toBeLessThan(64 * 1024 * 1024);
    console.info(
      `import ${rows} rows, ${(size / 1048576).toFixed(0)} MiB: ${(ms / 1000).toFixed(1)} s (${(size / 1048576 / (ms / 1000)).toFixed(1)} MiB/s), ${watch.reads.length} reads, heap peak +${(grew / 1048576).toFixed(1)} MiB`,
    );
  }, 3_600_000);

  it("rolls back on a refused row, the new table with it, and says its line", async () => {
    const m = await live({ "~/gen/bad.csv": "n,word\n1,one\n2,two\nthree,3\n4,four\n" }, fresh());
    await dropped(m, "~/gen/bad.csv");
    await m.app.importRun();
    await m.settle();
    expect(latest(m)?.problem).toBe(
      'Rolled back, nothing was imported: Line 3: invalid input syntax for type integer: "three"',
    );
    expect(await server.admin("SELECT count(*) FROM pg_class WHERE relname = 'bad'")).toBe("0");
  });

  it("in skip mode writes the refused rows with the server's reason and keeps the rest", async () => {
    const out = join(folder, "skip.rejects.csv");
    const text = `n,word\n${Array.from({ length: 30_000 }, (_, i) => (i % 9_999 === 5 ? `x${i},bad` : `${i},w${i}`)).join("\n")}\n`;
    const m = await live({ "~/gen/skip.csv": text }, fresh(), out);
    await dropped(m, "~/gen/skip.csv");
    m.app.importChange({ onError: "skip" });
    await m.settle();
    await m.app.importRun();
    await m.settle();
    expect(m.view.said.at(-1)).toBe(
      "Imported 29,997 rows into skip by COPY in one transaction; 3 rows refused went to the reject file.",
    );
    expect(await server.admin("SELECT count(*) || ':' || sum(n) FROM skip")).toBe(
      `29997:${(29_999 * 30_000) / 2 - 5 - 10_004 - 20_003}`,
    );
    expect(readFileSync(out, "utf8").split("\n").slice(0, 3)).toEqual([
      "row,reason,n,word",
      '6,"invalid input syntax for type integer: ""x5""",x5,bad',
      '10005,"invalid input syntax for type integer: ""x10004""",x10004,bad',
    ]);
  }, 120_000);

  it("leaves nothing on Cancel", async () => {
    const watch = fresh();
    const m = await live({ "~/gen/gone.csv": HEADER.length + 200_000 * ROW }, watch);
    await dropped(m, "~/gen/gone.csv");
    m.app.importChange({ column: [0, { type: "bigint" }] });
    await m.settle();
    watch.first = () => {
      watch.first = undefined;
      m.app.importCancel();
    };
    await m.app.importRun();
    await m.settle();
    expect(latest(m)?.problem).toBe("Rolled back, nothing was imported: Cancelled");
    expect(await server.admin("SELECT count(*) FROM pg_class WHERE relname = 'gone'")).toBe("0");
  }, 120_000);
});
