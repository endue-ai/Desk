import { NATIVE_CSS } from "./native-css";
import { cssVariables, type ThemeTokens, tokens } from "./tokens";

/**
 * The tokens as one `:root` rule, then the rules that make the engine's own parts (scrollbars,
 * checkboxes, selects) follow the theme (native-css.ts): `dist/tokens.css`, which the app serves at
 * `/_desk/tokens.css` to every page, and `src/tokens.css`, the committed copy the shell imports (a
 * test keeps them equal).
 */
export function tokensCss(theme: ThemeTokens = tokens): string {
  const lines = Object.entries(cssVariables(theme)).map(([name, value]) => `  ${name}: ${value};`);
  return `/* GENERATED by @endue-ai/ui from src/tokens.ts and src/native-css.ts (pnpm --filter @endue-ai/ui build, then copy dist/tokens.css here). Do not edit. */\n:root {\n${lines.join("\n")}\n}\n\n${NATIVE_CSS}`;
}
