import { cssVariables, type ThemeTokens, tokens } from "./tokens";

/**
 * The tokens as one `:root` rule: `dist/tokens.css`, which the app serves at `/_desk/tokens.css`,
 * and `src/tokens.css`, the committed copy the shell imports (a test keeps them equal).
 */
export function tokensCss(theme: ThemeTokens = tokens): string {
  const lines = Object.entries(cssVariables(theme)).map(([name, value]) => `  ${name}: ${value};`);
  return `/* GENERATED by @endue-ai/ui from src/tokens.ts (pnpm --filter @endue-ai/ui build, then copy dist/tokens.css here). Do not edit. */\n:root {\n${lines.join("\n")}\n}\n`;
}
