/** A component's or property's label: Korean from the table, English from the camelCase name. */
export function partLabel(lang: StudioLang, name: string): string {
  if (lang === "ko" && PARTS_KO[name]) return PARTS_KO[name] as string;
  const words = name.replace(/([A-Z])/g, " $1").toLowerCase();
  return words.charAt(0).toUpperCase() + words.slice(1);
}
