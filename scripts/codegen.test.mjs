import assert from "node:assert/strict";
import { describe, it } from "node:test";
import { generate, OUTPUTS } from "./codegen.mjs";

describe("codegen", () => {
  const first = generate();

  it("writes the four generated files", () => {
    assert.deepEqual(Object.keys(first).sort(), [...OUTPUTS].sort());
  });

  it("is deterministic: a second run is byte-identical", () => {
    const second = generate();
    for (const path of OUTPUTS) assert.equal(second[path], first[path], `${path} differs`);
  });

  it("marks every file GENERATED on its first line", () => {
    for (const path of OUTPUTS) {
      const firstLine = first[path].split("\n")[0];
      assert.match(firstLine, /^\/\/ GENERATED by scripts\/codegen\.mjs/, path);
    }
  });

  it("emits a Rust type and a TypeScript type for every bridge request", () => {
    const rust = first["crates/desk-bridge/src/generated.rs"];
    const ts = first["packages/bridge/src/generated.ts"];
    for (const name of [
      "FsReadRequest",
      "ProcSpawnRequest",
      "NetFetchRequest",
      "PermRevokeRequest",
    ]) {
      assert.match(rust, new RegExp(`pub struct ${name} \\{`), `${name} in Rust`);
      assert.match(ts, new RegExp(`export interface ${name} \\{`), `${name} in TypeScript`);
    }
  });

  it("emits the init.yaml types from specs/init/v0", () => {
    const rust = first["crates/desk-bridge/src/generated.rs"];
    const ts = first["packages/bridge/src/generated.ts"];
    for (const name of ["InitDocument", "InitPlugins", "InitSync"]) {
      assert.match(rust, new RegExp(`pub struct ${name} \\{`), `${name} in Rust`);
      assert.match(ts, new RegExp(`export interface ${name} \\{`), `${name} in TypeScript`);
    }
    assert.match(rust, /"https:\/\/endue\.ai\/specs\/init\/v0\/init\.schema\.json"/);
  });

  it("emits the item, view and connector types, and the new plugin kinds and permission", () => {
    const rust = first["crates/desk-bridge/src/generated.rs"];
    const ts = first["packages/bridge/src/generated.ts"];
    for (const name of [
      "ItemQuery",
      "ItemPage",
      "View",
      "ConnectorManifest",
      "ConnectorStatus",
      "DataReadPermission",
    ]) {
      assert.match(rust, new RegExp(`pub struct ${name} \\{`), `${name} in Rust`);
      assert.match(ts, new RegExp(`export interface ${name} \\{`), `${name} in TypeScript`);
    }
    for (const name of ["Item", "ItemChange"]) {
      assert.match(rust, new RegExp(`pub enum ${name} \\{`), `${name} in Rust`);
      assert.match(ts, new RegExp(`export type ${name} =`), `${name} in TypeScript`);
    }
    const kinds = /pub enum PluginKind \{[^}]*\}/.exec(rust)?.[0] ?? "";
    for (const kind of ["connector", "view", "theme"])
      assert.ok(kinds.includes(`#[serde(rename = "${kind}")]`), `PluginKind ${kind} in Rust`);
    assert.match(ts, /export type PluginKind =[^;]*"connector"\s*\|\s*"view"\s*\|\s*"theme";/);
    for (const file of ["item/v0/item", "item/v0/query", "view/v0/view", "connector/v0/connector"])
      assert.ok(
        rust.includes(`"https://endue.ai/specs/${file}.schema.json"`),
        `${file} in SCHEMAS`,
      );
  });
});
