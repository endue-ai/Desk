#!/usr/bin/env node
// just codegen: specs/ → Rust and TypeScript types. Deterministic: same specs, same bytes.
//   bridge + plugin schemas → crates/desk-bridge/src/generated.rs, packages/bridge/src/generated.ts
//   brain openapi.yaml      → crates/desk-brain/src/generated.rs,  packages/bridge/src/brain.generated.ts
import { execFileSync } from "node:child_process";
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { pathToFileURL } from "node:url";
import { loadAll, ROOT } from "./codegen/load.mjs";
import { buildModel } from "./codegen/model.mjs";
import { emitRust } from "./codegen/rust.mjs";
import { emitTs } from "./codegen/ts.mjs";

export const OUTPUTS = [
  "crates/desk-bridge/src/generated.rs",
  "packages/bridge/src/generated.ts",
  "crates/desk-brain/src/generated.rs",
  "packages/bridge/src/brain.generated.ts",
];

const header = (from) => [
  `GENERATED by scripts/codegen.mjs from ${from}. DO NOT EDIT.`,
  "Change the specs, then run `just codegen`.",
];

function rustfmt(source) {
  return execFileSync("rustfmt", ["--edition", "2024"], {
    input: source,
    encoding: "utf8",
    cwd: ROOT,
  });
}

function biome(source, path) {
  const bin = join(ROOT, "node_modules/.bin/biome");
  return execFileSync(bin, ["format", `--stdin-file-path=${path}`], {
    input: source,
    encoding: "utf8",
    cwd: ROOT,
  });
}

function schemaIncludes(docs) {
  const rows = docs.map((doc) => {
    const file = new URL(doc.$id).pathname.slice(1);
    return `    (${JSON.stringify(doc.$id)}, include_str!("../../../${file}")),`;
  });
  return [
    "/// Every bridge and plugin JSON Schema document as `($id, json)`, for validation at run time.",
    "pub const SCHEMAS: &[(&str, &str)] = &[",
    ...rows,
    "];",
    "",
  ].join("\n");
}

/** Generate every output in memory: { path: contents }. */
export function generate(root = ROOT) {
  const specs = loadAll(root);
  const bridge = buildModel(specs.bridge);
  const brain = buildModel(specs.brain);
  const bundle = specs.brain[0];
  const bundleJson = JSON.stringify(bundle, null, 2);
  const fromBridge = header("specs/bridge/v0 and specs/plugin/v0");
  const fromBrain = header("specs/brain/v0/openapi.yaml");
  return {
    "crates/desk-bridge/src/generated.rs": rustfmt(
      emitRust(bridge, { header: fromBridge, extra: schemaIncludes(specs.bridge) }),
    ),
    "packages/bridge/src/generated.ts": biome(
      emitTs(bridge, { header: fromBridge, methods: true }),
      "packages/bridge/src/generated.ts",
    ),
    "crates/desk-brain/src/generated.rs": rustfmt(
      emitRust(brain, {
        header: fromBrain,
        extra: [
          "/// The component schemas of specs/brain/v0/openapi.yaml as one JSON Schema document.",
          `pub const BRAIN_SCHEMA_JSON: &str = r##"${bundleJson}"##;`,
          "",
        ].join("\n"),
      }),
    ),
    "packages/bridge/src/brain.generated.ts": biome(
      emitTs(brain, {
        header: fromBrain,
        extra: [
          "/** The component schemas of specs/brain/v0/openapi.yaml as one JSON Schema document. */",
          `export const brainSchema = ${bundleJson};`,
          "",
        ].join("\n"),
      }),
      "packages/bridge/src/brain.generated.ts",
    ),
  };
}

function main() {
  const outputs = generate();
  for (const [path, contents] of Object.entries(outputs)) {
    const file = join(ROOT, path);
    const changed = !existsSync(file) || readFileSync(file, "utf8") !== contents;
    if (changed) writeFileSync(file, contents);
    console.log(`${changed ? "wrote    " : "unchanged"} ${path}`);
  }
}

if (import.meta.url === pathToFileURL(process.argv[1] ?? "").href) main();
