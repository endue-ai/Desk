import assert from "node:assert/strict";
import { readdirSync, readFileSync } from "node:fs";
import { join } from "node:path";
import { describe, it } from "node:test";
import { BUNDLE, ENTRY_PACKAGES, expected, ROOT, VENDOR, versions } from "./vendor-codemirror.mjs";

describe("vendor-codemirror", () => {
  const files = expected();

  it("the committed bundle in plugins/database/ui/vendor/editor matches the pinned packages", () => {
    assert.deepEqual(readdirSync(VENDOR).sort(), Object.keys(files).sort());
    for (const [name, text] of Object.entries(files)) {
      assert.equal(
        readFileSync(join(VENDOR, name), "utf8"),
        text,
        `${name} differs: run node scripts/vendor-codemirror.mjs`,
      );
    }
  });

  it("every bundled package is pinned to one exact version", () => {
    const manifest = JSON.parse(readFileSync(join(ROOT, "package.json"), "utf8"));
    const pinned = versions();
    for (const name of [...ENTRY_PACKAGES, ...Object.keys(pinned)]) {
      assert.ok(pinned[name], `${name} is not bundled`);
      assert.equal(
        manifest.devDependencies[name],
        pinned[name],
        `${name} is not pinned in package.json`,
      );
      assert.match(pinned[name], /^\d+\.\d+\.\d+$/u, `${name} has a range`);
    }
    assert.match(manifest.devDependencies.esbuild, /^\d+\.\d+\.\d+$/u, "the bundler is pinned");
    assert.match(
      files.VERSIONS,
      new RegExp(`^esbuild ${manifest.devDependencies.esbuild} \\(bundler\\)$`, "mu"),
    );
  });

  it("every bundled package's licence is beside the bundle, and each is MIT", () => {
    for (const name of Object.keys(versions())) {
      const at = files.LICENSE.indexOf(`${name} `);
      assert.ok(at >= 0, `${name} has no licence`);
      const body = files.LICENSE.slice(at, files.LICENSE.indexOf("\n----\n", at) >>> 0);
      assert.match(
        body,
        /MIT License|Permission is hereby granted, free of charge/u,
        `${name} is not MIT`,
      );
    }
  });

  it("the bundle loads nothing: no import, no fetch of its own, no source map", () => {
    const text = files[BUNDLE];
    assert.doesNotMatch(text, /(^|[;}\s])import\s*[\s{*("'`]/u, "an import statement");
    assert.doesNotMatch(text, /\bimport\(/u, "a dynamic import");
    assert.doesNotMatch(text, /\brequire\(/u, "a require");
    assert.doesNotMatch(text, /sourceMappingURL/u, "a source map comment");
    assert.doesNotMatch(
      text,
      /\bfetch\(|XMLHttpRequest|WebSocket|importScripts/u,
      "a network call",
    );
    const urls = new Set(text.match(/https?:\/\/[^\s"'`)]+/gu) ?? []);
    assert.deepEqual([...urls], ["http://www.w3.org/2000/svg"], "only the SVG namespace");
    assert.ok(text.startsWith("// GENERATED by scripts/vendor-codemirror.mjs"), "the header");
  });
});
