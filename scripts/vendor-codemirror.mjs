// Bundles the database SQL editor and Notes' plain-text viewport from the CodeMirror packages the root
// package.json pins to exact versions into one ES module,
// in each plugin's ui/vendor/editor folder, with every bundled package's licence and a
// VERSIONS file (ADR 0282); that folder is the editor's alone. CodeMirror ships as packages
// that import each other by bare name, which a plugin page cannot resolve, so esbuild (pinned as well)
// joins them; its output is the same for the same versions. `node scripts/vendor-codemirror.mjs`
// writes the folder; its test checks the committed copy matches, as vendor-xterm's does.
import { mkdirSync, readdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { buildSync, version as esbuildVersion } from "esbuild";

export const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
export const VENDOR = join(ROOT, "plugins/database/ui/vendor/editor");
export const BUNDLE = "editor-component.mjs";

/** The packages whose whole public API the bundle exports; the rest come in as their imports. */
export const ENTRY_PACKAGES = [
  "@codemirror/state",
  "@codemirror/view",
  "@codemirror/commands",
  "@codemirror/search",
  "@codemirror/autocomplete",
  "@codemirror/language",
  "@codemirror/lint",
];

const HEADER = [
  "// GENERATED by scripts/vendor-codemirror.mjs from the packages VERSIONS names (ADR 0282).",
  "// Third-party code under the MIT licence (LICENSE beside it): update by bumping the pins and",
  "// running the script, never by hand.",
  "",
].join("\n");

/** The package an esbuild input path belongs to: `node_modules/.pnpm/x/node_modules/<name>/...`. */
export function packageOf(/** @type {string} */ input) {
  const parts = input.split("/");
  const at = parts.lastIndexOf("node_modules");
  if (at < 0) return undefined;
  const first = parts[at + 1] ?? "";
  return first.startsWith("@") ? `${first}/${parts[at + 2]}` : first;
}

const NOTE_EXPORTS = [
  'export { EditorState } from "@codemirror/state";',
  'export { EditorView, keymap } from "@codemirror/view";',
  'export { defaultKeymap, history, historyKeymap } from "@codemirror/commands";',
].join("\n");

/** @param {"database" | "notes"} target */
function bundle(target = "database") {
  const result = buildSync({
    stdin: {
      contents:
        target === "notes"
          ? NOTE_EXPORTS
          : ENTRY_PACKAGES.map((name) => `export * from "${name}";`).join("\n"),
      resolveDir: ROOT,
      sourcefile: "codemirror-entry.js",
      loader: "js",
    },
    bundle: true,
    format: "esm",
    platform: "browser",
    target: "es2022",
    write: false,
    metafile: true,
    legalComments: "none",
    minify: true,
    logLevel: "silent",
  });
  const file = result.outputFiles[0];
  if (!file || !result.metafile) throw new Error("esbuild wrote no bundle");
  const inputs = Object.keys(result.metafile.inputs);
  /** @type {Map<string, string>} name -> its folder */
  const packages = new Map();
  for (const input of inputs) {
    const name = packageOf(input);
    if (!name) continue;
    const at = input.lastIndexOf(`node_modules/${name}/`);
    const folder = join(ROOT, input.slice(0, at + `node_modules/${name}`.length));
    const known = packages.get(name);
    if (known && known !== folder) throw new Error(`${name} is bundled from two folders`);
    packages.set(name, folder);
  }
  return { text: file.text, packages };
}

/** Every bundled package and its installed version, sorted by name. */
export function versions() {
  const { packages } = bundle();
  return Object.fromEntries(
    [...packages.entries()]
      .sort(([a], [b]) => a.localeCompare(b))
      .map(([name, folder]) => [
        name,
        JSON.parse(readFileSync(join(folder, "package.json"), "utf8")).version,
      ]),
  );
}

/** What ui/vendor/editor must hold: file name -> text. */
export function expected(/** @type {"database" | "notes"} */ target = "database") {
  const { text, packages } = bundle(target);
  const names = [...packages.keys()].sort((a, b) => a.localeCompare(b));
  const pinned = Object.fromEntries(
    names.map((name) => [
      name,
      JSON.parse(readFileSync(join(packages.get(name) ?? "", "package.json"), "utf8")).version,
    ]),
  );
  const licence = names
    .map((name) => {
      const folder = packages.get(name) ?? "";
      const file = readdirSync(folder).find((f) => /^licen[cs]e/iu.test(f));
      if (!file) throw new Error(`${name} has no licence file`);
      const body = readFileSync(join(folder, file), "utf8").trim();
      return `${name} ${pinned[name]}\n\n${body}\n`;
    })
    .join("\n----\n\n");
  const lines = names.map((name) => `${name} ${pinned[name]}`);
  return {
    [BUNDLE]: HEADER + text,
    LICENSE: licence,
    VERSIONS: `${lines.join("\n")}\nesbuild ${esbuildVersion} (bundler)\n`,
  };
}

export function vendor(/** @type {"database" | "notes"} */ target = "database") {
  const folder = target === "database" ? VENDOR : join(ROOT, "plugins/notes/ui/vendor/editor");
  const files = expected(target);
  rmSync(folder, { recursive: true, force: true });
  mkdirSync(folder, { recursive: true });
  for (const [name, text] of Object.entries(files)) writeFileSync(join(folder, name), text);
  return Object.keys(files).sort();
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  for (const name of vendor()) console.log(`vendored database/${name}`);
  for (const name of vendor("notes")) console.log(`vendored notes/${name}`);
}
